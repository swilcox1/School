def moveup(number):
		if number > 0:
			for i in range(number):
				move(North)
		elif number < 0:
			for i in range(number * -1):
				move(South)

def moveside(number):
		if number > 0:
			for i in range(number):
				move(East)
		elif number < 0:
			for i in range(number * -1):
				move(West)
def plant_pattern(pattern):

	global plump_pumpkin_count

	if plump_pumpkin_count == (len(pumpkin_map)):
		harvest_pumpkins = True
	else:
		harvest_pumpkins = False
	plump_pumpkin_count = 0


	plant_dict = {
		"p": (Entities.Pumpkin),
		"t": (Entities.Tree),
		"b": (Entities.Bush),
		"g": (Entities.Grass),
		"c": (Entities.Carrot)
		}


	#Identifies the dimensions required for pattern
	x = get_pos_x()
	y = get_pos_y()
	row_count = []
	col_count = len(pattern)
	for i in range(col_count):
		row_count.append(len(pattern[i]))

	for j in range(col_count):
		for k in range(row_count[1]):
			x = get_pos_x()
			y = get_pos_y()

			x_dif = j - x
			y_dif = k - y


			if x_dif != 0:
				moveside(x_dif)
			if y_dif != 0:
				moveup(y_dif)

			if get_ground_type() == Grounds.Grassland:
				till()
			if can_harvest() == True and get_entity_type() != Entities.Pumpkin:
				harvest()
			elif can_harvest() == True:
				global plump_pumpkin_count
				plump_pumpkin_count = plump_pumpkin_count +1



				if harvest_pumpkins == True:
					harvest()
					harvest_pumpkins = False





			plant_numb = pattern[j][k]
			plant(plant_dict[plant_numb])



